/**
 * Hybrid Gemini AI Budget Advisor Service
 *
 * Architecture & Privacy Rules:
 * 1. Optional intelligence layer over the deterministic Smart Budget engine.
 * 2. ZERO key leakage: Key is retrieved ONLY at runtime from localStorage `mm_gemini_api_key`.
 *    NEVER uses VITE_ or import.meta.env keys, NEVER creates .env files, and sends the key
 *    exclusively in the `x-goog-api-key` HTTP header (never in URLs).
 * 3. Explicit consent gate: No data leaves the device unless `mm_gemini_ai_consent` is true.
 * 4. Data minimization: Only anonymous aggregated totals are transmitted (totals per category/day).
 *    Never transmits account names, 16-digit IDs, emails, or free-text notes (except the single
 *    note explicitly submitted by the user for context classification).
 * 5. Prompt injection defense: Free-text note is treated as untrusted data and strictly delimited.
 * 6. Dual-model resilience: Primary `gemini-2.5-flash`, automatic fallback to `gemini-2.0-flash` on 404/429/5xx.
 * 7. Operational safeguards: 8-second AbortController timeout, 24-hour TTL cache (`mm_ai_advisor_cache`),
 *    monthly usage counter (`mm_ai_request_counter`), and in-memory 10-second throttle per feature.
 * 8. Strict response validation: Percentages must sum to 100, scenarios must belong to the allowed set,
 *    and currency amounts are NEVER generated by the model (derived solely from deterministic engine).
 */

