function computeCacheKey(feature: string, inputPayload: any): string {
  const str = `${feature}:${JSON.stringify(inputPayload)}`;
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return `ai_cache_${feature}_${Math.abs(hash)}`;
}

function getFromCache<T>(cacheKey: string): T | null {
  try {
    const raw = localStorage.getItem(AI_CACHE_STORAGE_KEY);
    if (!raw) return null;
    const store: Record<string, { timestamp: number; data: any }> = JSON.parse(raw);
    const item = store[cacheKey];
    if (!item) return null;
    if (Date.now() - item.timestamp > AI_CACHE_TTL_MS) {
      delete store[cacheKey];
      localStorage.setItem(AI_CACHE_STORAGE_KEY, JSON.stringify(store));
      return null;
    }
    return item.data as T;
  } catch {
    return null;
  }
}

function saveToCache(cacheKey: string, data: any): void {
  try {
    const raw = localStorage.getItem(AI_CACHE_STORAGE_KEY);
    const store: Record<string, { timestamp: number; data: any }> = raw ? JSON.parse(raw) : {};
    store[cacheKey] = { timestamp: Date.now(), data };
    localStorage.setItem(AI_CACHE_STORAGE_KEY, JSON.stringify(store));
  } catch {}
}

export function clearAICache(): void {
  try {
    localStorage.removeItem(AI_CACHE_STORAGE_KEY);
  } catch {}
}

const lastRequestTimeByFeature: Record<string, number> = {};

function isFeatureRateLimited(feature: string): boolean {
  const now = Date.now();
  const lastTime = lastRequestTimeByFeature[feature] || 0;
  return now - lastTime < AI_FEATURE_THROTTLE_MS;
}

function recordFeatureRequest(feature: string): void {
  lastRequestTimeByFeature[feature] = Date.now();
}

