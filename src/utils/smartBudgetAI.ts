// ============================================================================

export interface RecommendRebalanceParams {
  deficitMinor: number;
  deficitPool: 'daily' | 'outings';
  outingsRemainingMinor: number;
  dailyRemainingMinor: number;
  savingsTotalMinor: number;
  daysRemaining: number;
  currency: string;
  language?: 'ar' | 'en';
}

export interface RebalanceRecommendation {
  recommendedScenario: 'mild_rebalance' | 'deep_freeze' | 'savings_rescue';
  reasoning: string;
  source: 'ai' | 'deterministic';
}

export async function recommendRebalanceScenario(
  params: RecommendRebalanceParams
): Promise<RebalanceRecommendation> {
  const language = params.language || 'en';
  const isArabic = language === 'ar';
  const deficit = Math.max(1, params.deficitMinor);
  const outingsRem = params.outingsRemainingMinor;
  const dailyRem = params.dailyRemainingMinor;
  const savingsTotal = params.savingsTotalMinor;
  const daysRem = Math.max(1, params.daysRemaining);

  // Deterministic Decision Matrix:
  // Scenario 1: mild_rebalance (Trim Outings: If outings pool has enough to absorb deficit)
  // Scenario 2: deep_freeze (Daily Freeze: If daily pool has breathing room to spread the trim)
  // Scenario 3: savings_rescue (Emergency Savings Absorption: When living essentials must be protected)
  let deterministicScenario: 'mild_rebalance' | 'deep_freeze' | 'savings_rescue' = 'mild_rebalance';
  let deterministicReasoning = '';

  if (outingsRem >= deficit) {
    deterministicScenario = 'mild_rebalance';
    deterministicReasoning = isArabic
      ? 'نوصي بترحيل العجز من ميزانية الخروجات (سيناريو التهدئة). رصيد الترفيه المتبقي كافٍ لتغطية العجز دون المساس بمصروفك اليومي الأساسي أو مدخراتك.'
      : 'We recommend trimming your Outings pool (Mild Rebalance). Your remaining leisure balance covers the deficit completely without impacting your essential daily living or savings.';
  } else if (dailyRem > deficit * 1.5 && daysRem > 3) {
    deterministicScenario = 'deep_freeze';
    deterministicReasoning = isArabic
      ? 'نوصي بتجميد جزئي للمصروف اليومي (سيناريو التجميد). توزيع العجز على الأيام المتبقية يقلص المصروف اليومي قليلاً مع الحفاظ التام على كامل مدخراتك.'
      : 'We recommend a temporary Daily Freeze. Spreading the deficit across remaining days slightly moderates your daily burn rate while keeping your savings untouched.';
  } else {
    deterministicScenario = 'savings_rescue';
    deterministicReasoning = isArabic
      ? 'نوصي بالامتصاص من مدخرات الطوارئ (سيناريو الإنقاذ). العجز يتجاوز الفائض الترفيهي، واستيعابه من المدخرات يحمي معيشتك اليومية الأساسية حتى نهاية الدورة.'
      : 'We recommend an Emergency Savings Rescue. The deficit exceeds non-essential funds; absorbing it from savings protects your core daily living budget through cycle end.';
  }

  const deterministicFallback: RebalanceRecommendation = {
    recommendedScenario: deterministicScenario,
    reasoning: deterministicReasoning,
    source: 'deterministic',
  };

  // Check cache
  const cacheKey = computeCacheKey('rebalance_recommendation', {
    deficitPool: params.deficitPool,
    hasOutingsSurplus: outingsRem >= deficit,
    hasDailySurplus: dailyRem > deficit * 1.5,
    hasSavings: savingsTotal > deficit,
    daysRemaining: daysRem,
    language,
  });
  const cached = getFromCache<RebalanceRecommendation>(cacheKey);
  if (cached) return cached;

  if (isFeatureRateLimited('rebalance_recommendation')) {
    return deterministicFallback;
  }
  recordFeatureRequest('rebalance_recommendation');

  const prompt = `You are an expert financial advisor recommending one of 3 rebalancing actions:
1. "mild_rebalance": Trim recreational outings funds to absorb deficit. Preferred if outings has sufficient surplus.
2. "deep_freeze": Tighten everyday daily living expenses slightly across remaining days to absorb deficit without touching savings.
3. "savings_rescue": Absorb from savings reserves when essential daily living would otherwise fall below safe levels.

Current cycle situation:
- Deficit in pool: ${params.deficitPool}
- Outings pool balance status: ${outingsRem >= deficit ? 'Can absorb deficit' : 'Insufficient'}
- Daily living funds status: ${dailyRem > deficit * 1.5 ? 'Moderate flexibility' : 'Tight/Depleted'}
- Savings reserve status: ${savingsTotal > deficit ? 'Available' : 'Low'}
- Days remaining in cycle: ${daysRem}
Language for reasoning: ${isArabic ? 'Arabic' : 'English'}

Select the single best scenario among ("mild_rebalance", "deep_freeze", "savings_rescue") and explain why concisely.

Output schema:
{
  "recommendedScenario": "mild_rebalance" | "deep_freeze" | "savings_rescue",
  "reasoning": string
}`;

  const responseSchema = {
    type: 'OBJECT',
    properties: {
      recommendedScenario: {
        type: 'STRING',
        enum: ['mild_rebalance', 'deep_freeze', 'savings_rescue'],
      },
      reasoning: { type: 'STRING' },
    },
    required: ['recommendedScenario', 'reasoning'],
  };

  const aiResult = await callGeminiRest(prompt, responseSchema);

  if (aiResult && typeof aiResult === 'object') {
    const sc = aiResult.recommendedScenario;
    const rsn = typeof aiResult.reasoning === 'string' ? aiResult.reasoning.trim() : '';

    if (['mild_rebalance', 'deep_freeze', 'savings_rescue'].includes(sc) && rsn.length > 0) {
      const validResult: RebalanceRecommendation = {
        recommendedScenario: sc,
        reasoning: rsn,
        source: 'ai',
      };
      saveToCache(cacheKey, validResult);
      return validResult;
    }
  }

  return deterministicFallback;
}
