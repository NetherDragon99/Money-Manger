// CORE GEMINI REST ADAPTER (HYBRID RESOLUTION: PERSONAL -> PROXY -> SHARED -> DETERMINISTIC)
// ============================================================================

async function executeDirectGeminiCall(
  model: string,
  apiKey: string,
  prompt: string,
  responseSchema?: any
): Promise<any | null> {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), GEMINI_API_TIMEOUT_MS);

  try {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;
    const generationConfig: Record<string, any> = {
      temperature: 0.2,
      responseMimeType: 'application/json',
    };
    if (responseSchema) {
      generationConfig.responseSchema = responseSchema;
    }

    const requestBody = {
      contents: [
        {
          parts: [{ text: prompt }],
        },
      ],
      generationConfig,
    };

    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-goog-api-key': apiKey,
      },
      body: JSON.stringify(requestBody),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (res.ok) {
      const json = await res.json();
      const candidateText = json?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (candidateText && typeof candidateText === 'string') {
        const parsed = JSON.parse(candidateText.trim());
        incrementAIMonthlyUsage();
        return parsed;
      }
    } else {
      console.warn(`[SmartBudgetAI] Direct call to ${model} returned status ${res.status}`);
    }
  } catch (err: any) {
    clearTimeout(timeoutId);
    console.warn(
      `[SmartBudgetAI] Direct call to ${model} interrupted or timed out:`,
      err?.name || 'Error'
    );
  }

  return null;
}

async function executeProxyGeminiCall(
  proxyUrl: string,
  prompt: string,
  responseSchema?: any
): Promise<any | null> {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), GEMINI_API_TIMEOUT_MS);

  try {
    let idToken = '';
    if (auth.currentUser) {
      try {
        idToken = await auth.currentUser.getIdToken();
      } catch (tokenErr) {
        console.warn('[SmartBudgetAI] Failed to fetch Firebase ID token for proxy:', tokenErr);
      }
    }

    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
    };
    if (idToken) {
      headers['Authorization'] = `Bearer ${idToken}`;
    }

    const requestBody = {
      model: GEMINI_MODEL_PRIMARY,
      contents: [
        {
          parts: [{ text: prompt }],
        },
      ],
      generationConfig: {
        temperature: 0.2,
        responseMimeType: 'application/json',
        ...(responseSchema ? { responseSchema } : {}),
      },
    };

    const res = await fetch(proxyUrl, {
      method: 'POST',
      headers,
      body: JSON.stringify(requestBody),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (res.ok) {
      const json = await res.json();
      let candidateText = json?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!candidateText && typeof json === 'string') {
        candidateText = json;
      } else if (!candidateText && json?.text) {
        candidateText = json.text;
      } else if (!candidateText && json && typeof json === 'object' && !json.candidates) {
        incrementAIMonthlyUsage();
        return json;
      }

      if (candidateText && typeof candidateText === 'string') {
        const parsed = JSON.parse(candidateText.trim());
        incrementAIMonthlyUsage();
        return parsed;
      }
    } else {
      console.warn(`[SmartBudgetAI] Proxy call returned status ${res.status}`);
    }
  } catch (err: any) {
    clearTimeout(timeoutId);
    console.warn('[SmartBudgetAI] Proxy call failed or timed out:', err?.name || 'Error');
  }

  return null;
}

async function callGeminiRest(prompt: string, responseSchema?: any): Promise<any | null> {
  if (typeof navigator !== 'undefined' && !navigator.onLine) {
    return null;
  }
  if (!hasAIConsent()) {
    return null;
  }

  const modelsToTry = [GEMINI_MODEL_PRIMARY, GEMINI_MODEL_FALLBACK];

  // --------------------------------------------------------------------------
  // PRIORITY 1: User's personal key (localStorage mm_gemini_api_key synced at users/${uid}/secrets/gemini)
  // --------------------------------------------------------------------------
  const personalKey = getLocalGeminiApiKey();
  if (personalKey) {
    for (const model of modelsToTry) {
      const result = await executeDirectGeminiCall(model, personalKey, prompt, responseSchema);
      if (result) {
        return result;
      }
    }
  }

  // --------------------------------------------------------------------------
  // PRIORITY 2: Optional proxy URL (mm_ai_proxy_url or VITE_AI_PROXY_URL) with Firebase ID token
  // --------------------------------------------------------------------------
  const proxyUrl = getAIProxyUrl();
  if (proxyUrl) {
    const result = await executeProxyGeminiCall(proxyUrl, prompt, responseSchema);
    if (result) {
      return result;
    }
  }

  // --------------------------------------------------------------------------
  // PRIORITY 3: Shared default key fetched on-demand for signed-in users from RTDB app_config/gemini/apiKey
  // --------------------------------------------------------------------------
  const sharedKey = await getSharedDefaultApiKey();
  if (sharedKey) {
    for (const model of modelsToTry) {
      const result = await executeDirectGeminiCall(model, sharedKey, prompt, responseSchema);
      if (result) {
        return result;
      }
    }
    // Invalidate session cache if shared key failed
    inMemorySharedApiKey = null;
  }

  // --------------------------------------------------------------------------
  // PRIORITY 4: Automatic silent fallback to deterministic engine
  // --------------------------------------------------------------------------
  return null;
}

