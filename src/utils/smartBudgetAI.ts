export interface PeriodicHealthAndWhatIfParams {
  cycleLength: number;
  daysRemaining: number;
  cycleProgressPercent: number;
  dailyPoolRemainingMinor: number;
  dailySuggestedRateMinor: number;
  outingsRemainingMinor: number;
  emergencySpentMinor: number;
  currency: string;
  whatIfExtraExpenseMinor?: number;
  whatIfPool?: 'daily' | 'outings' | 'emergency';
  language?: 'ar' | 'en';
}

export interface HealthAndWhatIfAdvice {
  status: 'healthy' | 'caution' | 'critical';
  runwayDaysRemaining: number;
  adviceText: string;
  whatIfAnalysis?: string;
  source: 'ai' | 'deterministic';
}

export async function evaluatePeriodicHealthAndWhatIf(
  params: PeriodicHealthAndWhatIfParams
): Promise<HealthAndWhatIfAdvice> {
  const language = params.language || 'en';
  const isArabic = language === 'ar';
  const daysRem = Math.max(1, params.daysRemaining);
  const dailyRem = params.dailyPoolRemainingMinor;
  const suggestedRate = Math.max(1, params.dailySuggestedRateMinor);
  const outingsRem = params.outingsRemainingMinor;
  const emergencySpent = params.emergencySpentMinor;

  // Deterministic runway
  const runwayDays = Math.max(0, Math.floor(dailyRem / suggestedRate));

  let status: 'healthy' | 'caution' | 'critical' = 'healthy';
  let adviceText = '';

  if (dailyRem <= 0) {
    status = 'critical';
    adviceText = isArabic
      ? 'تنبيه حرج: تم استنفاد ميزانية المعيشة اليومية للدورة الحالية بالكامل. يوصى بتطبيق سيناريو إعادة التوازن لحماية استقرارك المالي.'
      : 'Critical: The daily living pool for this cycle is fully depleted. Applying a rebalance scenario is strongly advised to maintain financial stability.';
  } else if (runwayDays < daysRem - 2) {
    status = 'caution';
    adviceText = isArabic
      ? `تنبيه حذر: معدل الصرف الحالي يغطي حوالي ${runwayDays} أيام فقط من أصل ${daysRem} يوماً متبقية. خفض وتيرة المصروفات اليومية قليلاً سيضمن اكتمال الدورة بأمان.`
      : `Caution: Current daily allowance covers approximately ${runwayDays} days out of ${daysRem} remaining. Slightly moderating daily spend will ensure a smooth finish to the cycle.`;
  } else {
    status = 'healthy';
    adviceText = isArabic
      ? `وضع ممتاز: ميزانيتك اليومية متزنة تماماً وتغطي كامل الأيام المتبقية (${daysRem} يوماً) بمعدل صرف مريح.`
      : `Healthy: Your budget pace is on track to comfortably cover all ${daysRem} remaining days at the suggested daily rate.`;
  }

  let whatIfAnalysis: string | undefined = undefined;
  if (params.whatIfExtraExpenseMinor && params.whatIfExtraExpenseMinor > 0) {
    const extra = params.whatIfExtraExpenseMinor;
    const whatPool = params.whatIfPool || 'outings';
    if (whatPool === 'outings') {
      const remainingAfter = outingsRem - extra;
      if (remainingAfter >= 0) {
        whatIfAnalysis = isArabic
          ? 'تحليل سيناريو: ميزانية الخروجات المتبقية كافية لتغطية هذا المصروف بالكامل دون أي تأثير على المصروف اليومي الأساسي.'
          : 'What-If: Your remaining Outings pool easily absorbs this expense with zero impact on your core daily living allowance.';
      } else {
        const spill = Math.abs(remainingAfter);
        const newDailyRem = Math.max(0, dailyRem - spill);
        const newDailyRate = Math.floor(newDailyRem / daysRem);
        whatIfAnalysis = isArabic
          ? `تحليل سيناريو: هذا المصروف سيتجاوز ميزانية الخروجات؛ سيتأثر المصروف اليومي ليصبح المتبقي بمعدل أقل.`
          : `What-If: This expense exceeds your Outings pool and will reduce your remaining daily allowance.`;
      }
    } else {
      const newDailyRem = Math.max(0, dailyRem - extra);
      const newRunway = Math.floor(newDailyRem / suggestedRate);
      whatIfAnalysis = isArabic
        ? `تحليل سيناريو: خصم هذا المبلغ من المعيشة اليومية سيقلص فترة الأمان المتبقية إلى نحو ${newRunway} يوماً.`
        : `What-If: Spending this from daily funds reduces your safe runway to approximately ${newRunway} days.`;
    }
  }

  const deterministicFallback: HealthAndWhatIfAdvice = {
    status,
    runwayDaysRemaining: runwayDays,
    adviceText,
    whatIfAnalysis,
    source: 'deterministic',
  };

  // Check cache
  const cacheKey = computeCacheKey('health_what_if', {
    cycleProgress: Math.round(params.cycleProgressPercent),
    daysRemaining: daysRem,
    dailyRemTier: Math.round(dailyRem / 1000),
    outingsTier: Math.round(outingsRem / 1000),
    whatIf: params.whatIfExtraExpenseMinor ? Math.round(params.whatIfExtraExpenseMinor / 1000) : 0,
    language,
  });
  const cached = getFromCache<HealthAndWhatIfAdvice>(cacheKey);
  if (cached) return cached;

  if (isFeatureRateLimited('health_what_if')) {
    return deterministicFallback;
  }
  recordFeatureRequest('health_what_if');

  const prompt = `You are an empathetic financial coach.
Evaluate the health of the user's current budget cycle and provide plain-language guidance:
- Cycle progress: ${Math.round(params.cycleProgressPercent)}% complete
- Days remaining: ${daysRem}
- Runway days covered by daily funds: ${runwayDays}
- Outings funds remaining status: ${outingsRem >= 0 ? 'Surplus' : 'Deficit'}
- Emergency expenses incurred: ${emergencySpent > 0 ? 'Yes' : 'None'}
${params.whatIfExtraExpenseMinor ? `- Hypothetical extra expense evaluated in pool: ${params.whatIfPool || 'outings'}` : ''}
Language for advice: ${isArabic ? 'Arabic' : 'English'}

Rules:
1. Provide a status: "healthy", "caution", or "critical".
2. Do NOT invent new currency figures. Plain qualitative explanation only.
3. Provide encouraging, actionable financial advice.

Output schema:
{
  "status": "healthy" | "caution" | "critical",
  "runwayDaysRemaining": number,
  "adviceText": string,
  "whatIfAnalysis": string or null
}`;

  const responseSchema = {
    type: 'OBJECT',
    properties: {
      status: {
        type: 'STRING',
        enum: ['healthy', 'caution', 'critical'],
      },
      runwayDaysRemaining: { type: 'INTEGER' },
      adviceText: { type: 'STRING' },
      whatIfAnalysis: { type: 'STRING' },
    },
    required: ['status', 'runwayDaysRemaining', 'adviceText'],
  };

  const aiResult = await callGeminiRest(prompt, responseSchema);

  if (aiResult && typeof aiResult === 'object') {
    const st = aiResult.status;
    const rDays = Number(aiResult.runwayDaysRemaining);
    const adv = typeof aiResult.adviceText === 'string' ? aiResult.adviceText.trim() : '';
    const wIf = typeof aiResult.whatIfAnalysis === 'string' ? aiResult.whatIfAnalysis.trim() : whatIfAnalysis;

    if (['healthy', 'caution', 'critical'].includes(st) && !isNaN(rDays) && adv.length > 0) {
      const validResult: HealthAndWhatIfAdvice = {
        status: st,
        runwayDaysRemaining: Math.max(0, rDays),
        adviceText: adv,
        whatIfAnalysis: wIf || undefined,
        source: 'ai',
      };
      saveToCache(cacheKey, validResult);
      return validResult;
    }
  }

  return deterministicFallback;
}

