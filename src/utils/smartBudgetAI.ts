export interface SuggestSalaryAllocationParams {
  plannedIncomeMajor: number;
  fixedObligationsMajor?: number;
  savingsMinPercent?: number;
  language?: 'ar' | 'en';
}

export interface SalaryAllocationSuggestion {
  savingsPercent: number;
  fixedPercent: number;
  outingsPercent: number;
  dailyPercent: number;
  explanation: string;
  source: 'ai' | 'deterministic';
}

export async function suggestSalaryAllocation(
  params: SuggestSalaryAllocationParams
): Promise<SalaryAllocationSuggestion> {
  const language = params.language || 'en';
  const isArabic = language === 'ar';
  const savingsMin = Math.max(5, params.savingsMinPercent || 10);
  const income = Math.max(0, params.plannedIncomeMajor);
  const fixed = Math.max(0, params.fixedObligationsMajor || 0);

  // Deterministic baseline calculation
  const fixedRatio = income > 0 ? Math.min(65, Math.round((fixed / income) * 100)) : 35;
  const deterministicFixed = Math.max(20, fixedRatio);
  const deterministicSavings = Math.max(savingsMin, 20);
  const remainingForLiving = Math.max(10, 100 - deterministicFixed - deterministicSavings);
  const deterministicOutings = Math.round(remainingForLiving * 0.35);
  const deterministicDaily = 100 - deterministicFixed - deterministicSavings - deterministicOutings;

  const deterministicFallback: SalaryAllocationSuggestion = {
    savingsPercent: deterministicSavings,
    fixedPercent: deterministicFixed,
    outingsPercent: deterministicOutings,
    dailyPercent: deterministicDaily,
    explanation: isArabic
      ? `توزيع قياسي حتمي: ${deterministicSavings}% مدخرات لبناء احتياطي الأمان، ${deterministicFixed}% للالتزامات والفواتير الثابتة، ${deterministicOutings}% للترفيه والخروجات، و${deterministicDaily}% لمصروفات المعيشة اليومية.`
      : `Deterministic baseline: ${deterministicSavings}% allocated to savings reserves, ${deterministicFixed}% for fixed obligations, ${deterministicOutings}% for recreational outings, and ${deterministicDaily}% for daily safe-to-spend living.`,
    source: 'deterministic',
  };

  // Check cache first
  const cacheKey = computeCacheKey('salary_allocation', {
    income,
    fixed,
    savingsMin,
    language,
  });
  const cached = getFromCache<SalaryAllocationSuggestion>(cacheKey);
  if (cached) return cached;

  // Rate limiting check
  if (isFeatureRateLimited('salary_allocation')) {
    return deterministicFallback;
  }
  recordFeatureRequest('salary_allocation');

  // AI Prompt
  const prompt = `You are a certified financial planning advisor.
Recommend optimal percentage allocations across 4 budget pools summing to EXACTLY 100%:
- savingsPercent: Minimum ${savingsMin}%. Must be >= ${savingsMin}.
- fixedPercent: Based on estimated fixed commitments (${fixed} out of ${income}).
- outingsPercent: Leisure, dining out, and fun.
- dailyPercent: Daily safe-to-spend for groceries, commuting, and routine living.

Total planned income: ${income}
Estimated fixed commitments: ${fixed}
Minimum required savings: ${savingsMin}%
Language for explanation: ${isArabic ? 'Arabic' : 'English'}

Provide an output conforming to this JSON schema:
{
  "savingsPercent": integer,
  "fixedPercent": integer,
  "outingsPercent": integer,
  "dailyPercent": integer,
  "explanation": string
}`;

  const responseSchema = {
    type: 'OBJECT',
    properties: {
      savingsPercent: { type: 'INTEGER' },
      fixedPercent: { type: 'INTEGER' },
      outingsPercent: { type: 'INTEGER' },
      dailyPercent: { type: 'INTEGER' },
      explanation: { type: 'STRING' },
    },
    required: ['savingsPercent', 'fixedPercent', 'outingsPercent', 'dailyPercent', 'explanation'],
  };

  const aiResult = await callGeminiRest(prompt, responseSchema);

  if (aiResult && typeof aiResult === 'object') {
    const s = Math.round(Number(aiResult.savingsPercent));
    const f = Math.round(Number(aiResult.fixedPercent));
    const o = Math.round(Number(aiResult.outingsPercent));
    const d = Math.round(Number(aiResult.dailyPercent));
    const exp = typeof aiResult.explanation === 'string' ? aiResult.explanation.trim() : '';

    if (
      !isNaN(s) && !isNaN(f) && !isNaN(o) && !isNaN(d) &&
      s >= savingsMin && f >= 0 && o >= 0 && d >= 0 &&
      s + f + o + d === 100 &&
      exp.length > 0
    ) {
      const validResult: SalaryAllocationSuggestion = {
        savingsPercent: s,
        fixedPercent: f,
        outingsPercent: o,
        dailyPercent: d,
        explanation: exp,
        source: 'ai',
      };
      saveToCache(cacheKey, validResult);
      return validResult;
    }
  }

  return deterministicFallback;
}

